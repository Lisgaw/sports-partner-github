// ─── Deep merge helper ────────────────────────────────────────────────────────
function deepMerge(target, source) {
  const result = { ...target };
  for (const key of Object.keys(source)) {
    if (source[key] && typeof source[key] === "object" && !Array.isArray(source[key])) {
      result[key] = deepMerge(target[key] ?? {}, source[key]);
    } else {
      result[key] = source[key];
    }
  }
  return result;
}

// ─── Process each locale file ─────────────────────────────────────────────────
const locales = ["tr", "en", "de", "es", "fr", "ja", "ko", "ru"];

for (const locale of locales) {
  const filePath = path.join(messagesDir, `${locale}.json`);
  const existing = JSON.parse(fs.readFileSync(filePath, "utf8"));
  const additions = ADDITIONS[locale] ?? {};
  const merged = deepMerge(existing, additions);
  // Write without BOM
  fs.writeFileSync(filePath, JSON.stringify(merged, null, 2), { encoding: "utf8" });
  console.log(`✅ Updated ${locale}.json`);
}

console.log("\n🎉 All locale files updated successfully!");
